import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import path from 'node:path'
const dir = path.resolve(import.meta.dirname, '..')
const output = path.join(dir, 'lib')
mkdirSync(output, { recursive: true })
copyFileSync(path.join(dir, 'src/server.mjs'), path.join(output, 'index.mjs'))
copyFileSync(path.join(dir, 'src/ops-read.mjs'), path.join(output, 'ops-read.mjs'))
copyFileSync(path.join(dir, 'src/session-read.mjs'), path.join(output, 'session-read.mjs'))
copyFileSync(path.join(dir, 'src/usage-read.mjs'), path.join(output, 'usage-read.mjs'))
copyFileSync(path.join(dir, 'src/agent-profile.mjs'), path.join(output, 'agent-profile.mjs'))
copyFileSync(path.join(dir, 'src/schedule-spec.mjs'), path.join(output, 'schedule-spec.mjs'))
copyFileSync(path.join(dir, 'src/schedule-read.mjs'), path.join(output, 'schedule-read.mjs'))
copyFileSync(path.join(dir, 'src/exec-policy.mjs'), path.join(output, 'exec-policy.mjs'))
const css = readFileSync(path.join(dir, 'src/client.css'), 'utf8')
const js = readFileSync(path.join(dir, 'src/client.js'), 'utf8')
const workbench = readFileSync(path.join(dir, 'src/workbench.js'), 'utf8')
const opsPages = readFileSync(path.join(dir, 'src/ops-pages.js'), 'utf8')
const usagePanel = readFileSync(path.join(dir, 'src/usage-panel.js'), 'utf8')
const agentProfileUI = readFileSync(path.join(dir, 'src/agent-profile-ui.js'), 'utf8')
const markdownEditor = readFileSync(path.join(dir, 'src/markdown-editor.js'), 'utf8')
const groupPanel = readFileSync(path.join(dir, 'src/group-panel.js'), 'utf8')
const schedulePanel = readFileSync(path.join(dir, 'src/schedule-panel.js'), 'utf8')
const execPolicyPanel = readFileSync(path.join(dir, 'src/exec-policy-panel.js'), 'utf8')
if (!js.includes('__CSS_TEXT__') || !js.includes('/*__WORKBENCH_CODE__*/'))
  throw Error('missing client asset marker')
writeFileSync(path.join(output, 'client.js'), js
  .replace('__CSS_TEXT__', () => JSON.stringify(css))
  .replace('/*__WORKBENCH_CODE__*/', () => opsPages + '\n' + usagePanel + '\n' + markdownEditor + '\n' + agentProfileUI + '\n' + groupPanel + '\n' + schedulePanel + '\n' + execPolicyPanel + '\n' + workbench))
console.log('Feishu web-admin built')
