/**
 * Pure helpers for the real-LLM / real-Feishu E2E harness.
 *
 * No I/O, no env reads inside this module (so it is unit-testable without any
 * credential). Credential VALUES are never returned, logged or embedded in
 * reports; only env-var NAMES are handled here.
 */

/** Env-var NAMES (never values) and what each unlocks. */
export const ENV_SPECS = Object.freeze({
  // --- real commercial LLM ---
  FEISHU_GATEWAY_TEST_LLM_KEY: {
    purpose: 'API key for the dedicated TEST LLM route (never a production key)',
    neededFor: ['llm:real'],
  },
  FEISHU_GATEWAY_TEST_LLM_BASE_URL: {
    purpose: 'OpenAI-compatible base URL of the real LLM provider, e.g. https://api.example.com/v1',
    neededFor: ['llm:real'],
  },
  FEISHU_GATEWAY_TEST_LLM_MODEL: {
    purpose: 'Real model id served by that endpoint',
    neededFor: ['llm:real'],
  },
  // --- real Feishu tenant ---
  FEISHU_GATEWAY_DEFAULT_APP_ID: {
    purpose: 'App ID of a DEDICATED Feishu test app (cli_ + 16 hex)',
    neededFor: ['feishu:live'],
  },
  FEISHU_GATEWAY_DEFAULT_APP_SECRET: {
    purpose: 'App Secret of that DEDICATED test app (read by the SDK from env, never logged)',
    neededFor: ['feishu:live'],
  },
  FEISHU_GATEWAY_TEST_ALLOWLIST: {
    purpose: 'Comma-separated open_id(s) of test user(s) allowed to talk to the bot',
    neededFor: ['feishu:live'],
  },
  FEISHU_GATEWAY_TEST_CHAT_ID: {
    purpose: 'Optional p2p chat_id for scripted message sending / log correlation',
    neededFor: [],
  },
  FEISHU_GATEWAY_TEST_USER_ACCESS_TOKEN: {
    purpose: 'Optional user_access_token enabling scripted sending AS a test user (otherwise send manually)',
    neededFor: [],
  },
})

/** Which env NAMES are required for a given mode combination. */
export function requiredEnvNames({ llmMode = 'mock', feishuMode = 'offline' } = {}) {
  const tags = new Set([`llm:${llmMode}`, `feishu:${feishuMode}`])
  return Object.entries(ENV_SPECS)
    .filter(([, spec]) => spec.neededFor.some((t) => tags.has(t)))
    .map(([name]) => name)
}

/**
 * Presence-only check. Returns NAMES only. Never includes or echoes values.
 * @returns {{present: string[], missing: string[], blocked: boolean}}
 */
export function checkEnv(env, opts = {}) {
  const present = []
  const missing = []
  for (const name of requiredEnvNames(opts)) {
    if (typeof env[name] === 'string' && env[name].length > 0 && !isPlaceholder(env[name])) present.push(name)
    else missing.push(name)
  }
  return { present, missing, blocked: missing.length > 0 }
}

function isPlaceholder(value) {
  const v = value.trim()
  return v === '' || /^x{4,}$/i.test(v) || /^cli_x{8,}$/i.test(v) || v.startsWith('your-') || v === 'changeme'
}

/** Validate an app id SHAPE only (value is never echoed). */
export function appIdShapeValid(appId) {
  return typeof appId === 'string' && /^cli_[0-9a-fA-F]{16}$/.test(appId)
}

/** Safe YAML scalar (JSON string is valid YAML). */
function y(value) {
  return JSON.stringify(String(value))
}

function yList(values) {
  return `[${values.map((v) => y(v)).join(', ')}]`
}

/**
 * Build the profile `cordis.patch.yml` content for an isolated DSH_HOME.
 * Values that are NOT secrets may be embedded; env-var NAMES are always used
 * for credentials (never their values).
 */
export function buildPatch({
  llmMode = 'mock',
  feishuMode = 'offline',
  hostMode = 'oneshot',
  mockLlmPort = 18080,
  daemonPort = 18091,
  stateDir,
  workspace,
  allowlist = [],
  providerId = 'test-route',
  baseURL = '',
  modelId = 'test-model',
  llmKeyEnv = 'FEISHU_GATEWAY_TEST_LLM_KEY',
  probeEnabled = true,
  replyTimeoutMs = 30000,
} = {}) {
  const lines = []
  lines.push('# GENERATED by scripts/e2e/setup.mjs — isolated test profile only.')
  lines.push('# Credential VALUES never appear here; only env-var NAMES are referenced.')
  lines.push('')

  // ---- LLM route -------------------------------------------------------
  lines.push('- id: llm-pi-ai')
  lines.push(`  name: ${y('@deepseek-ai/dsh-llm-pi-ai')}`)
  lines.push('  config:')
  lines.push('    providers:')
  lines.push(`      ${providerId}:`)
  lines.push(`        apiKeyEnv: ${y(llmKeyEnv)}`)
  lines.push(`        api: ${y('openai-completions')}`)
  lines.push(`        baseURL: ${y(llmMode === 'real' ? baseURL : `http://127.0.0.1:${mockLlmPort}/v1`)}`)
  lines.push('        models:')
  lines.push(`          - id: ${y(llmMode === 'real' ? modelId : 'mock-model')}`)
  lines.push(`            name: ${y(llmMode === 'real' ? 'Real Test Model' : 'Mock Test Model')}`)
  lines.push('            contextWindow: 8192')
  lines.push('            maxTokens: 2048')
  lines.push('            input: [text]')
  lines.push('')
  lines.push('- id: agent-default-model')
  lines.push(`  name: ${y('@deepseek-ai/dsh-agent-default-model')}`)
  lines.push('  config:')
  lines.push(`    provider: ${y(providerId)}`)
  lines.push(`    model: ${y(llmMode === 'real' ? modelId : 'mock-model')}`)
  lines.push('')

  // ---- Gateway ---------------------------------------------------------
  lines.push('- id: feishu-gateway')
  lines.push('  config:')
  lines.push('    bots:')
  lines.push('      - id: default')
  lines.push('        enabled: true')
  lines.push('        domain: feishu')
  lines.push(`        appIdEnv: ${y('FEISHU_GATEWAY_DEFAULT_APP_ID')}`)
  lines.push(`        appSecretEnv: ${y('FEISHU_GATEWAY_DEFAULT_APP_SECRET')}`)
  lines.push(`    allowlist: ${yList(feishuMode === 'live' ? allowlist : [])}`)
  lines.push('    allowGroups: false')
  lines.push(`    workspace: ${y(workspace)}`)
  lines.push(`    stateDir: ${y(stateDir)}`)
  lines.push('    dedupTtlMs: 86400000')
  lines.push('    maxTextLength: 8000')
  lines.push(`    replyTimeoutMs: ${Number(replyTimeoutMs)}`)
  lines.push('    sendRetries: 3')
  lines.push('    autoConnect: true')
  lines.push(`    offline: ${feishuMode === 'live' ? 'false' : 'true'}`)
  lines.push('    diagnoseOnStart: true')
  lines.push('')

  // ---- Test-only long-running Host -------------------------------------
  if (hostMode === 'daemon') {
    lines.push('# Long-running Host: real Feishu WS events need a persistent process.')
    lines.push('# dsh-headless is intentionally NOT in bundles in daemon mode.')
    lines.push('- insert:')
    lines.push(`    - name: ${y('./e2e-daemon.mjs')}`)
    lines.push('      config:')
    lines.push(`        port: ${Number(daemonPort)}`)
    lines.push('')
  }

  // ---- SessionBridge verification probe --------------------------------
  if (probeEnabled) {
    // The probe drives its OWN FeishuGateway, so it must NOT share the plugin's
    // stateDir (the exclusive .owner.lock would correctly refuse a second owner).
    lines.push('- insert:')
    lines.push(`    - name: ${y('./native-session-probe.mjs')}`)
    lines.push('      config:')
    lines.push(`        outFile: ${y(`${stateDir}-probe/probe-result.json`)}`)
    lines.push(`        stateDir: ${y(`${stateDir}-probe`)}`)
    lines.push(`        workspace: ${y(workspace)}`)
    lines.push('')
  }

  return lines.join('\n')
}

/** Bundles for a given host mode. Daemon mode drops the one-shot headless app. */
export function bundlesFor(hostMode, pluginName = 'dsh-plugin-feishu-gateway') {
  return hostMode === 'daemon'
    ? ['@deepseek-ai/dsh-base', pluginName]
    : ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless', pluginName]
}

