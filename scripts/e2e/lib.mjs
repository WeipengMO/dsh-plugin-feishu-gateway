/**
 * Default "remembered string". The runner overrides it from
 * `E2E_TOKEN` (env) so a substituted value flows probe → LLM → assertion.
 */
export const DEFAULT_TOKEN = 'GBM-7429'

const textOf = (x) => (typeof x === 'string' ? x : (x && typeof x.text === 'string' ? x.text : String(x ?? '')))
const hasToken = (text, token) => String(text).toUpperCase().includes(String(token).toUpperCase())

/**
 * Evaluate the 3-turn result produced by native-session-probe.mjs.
 * Real-model tolerant: a real LLM adds prose, so we check the token is present
 * rather than requiring an exact string.
 */
export function evaluateThreeTurns(result, token = DEFAULT_TOKEN) {
  const turns = Array.isArray(result?.turns) ? result.turns : []
  const replies = turns.map((t) => (t.replies || []).map(textOf).join(' | '))
  const sid = result?.sessionId || null
  const sameSid = Boolean(sid) && turns.length === 3 && turns.every((t) => t.sessionId === sid)
  const calls = (result?.bridgeCalls || []).map((c) => c.m)
  const disposeCalls = (result?.disposeCalls || []).length
  const snapshots = result?.snapshots || []
  const live = snapshots.length > 0 && snapshots.every((s) =>
    s.agentRegistryHas === true && s.sessionStoreHas === true && s.factoryPresent === true)
  return {
    turns: turns.length === 3,
    sameSessionId: sameSid,
    firstTurnAcknowledged: replies.length >= 1 && replies[0].trim().length > 0,
    secondTurnRecalls: replies.length >= 2 && hasToken(replies[1], token),
    thirdTurnRecalls: replies.length >= 3 && hasToken(replies[2], token),
    bridgeSequence: calls.join(',') === 'create,submit,waitForReply,resume,submit,waitForReply,resume,submit,waitForReply,dispose',
    handleDisposedOnce: disposeCalls === 1,
    servicesLive: live,
    noErrors: (result?.errors || []).length === 0,
    replies,
    sessionId: sid,
  }
}

/** Evaluate cross-host cold-resume result. */
export function evaluateResume(result, token = DEFAULT_TOKEN) {
  const turn = (result?.turns || [])[0]
  const reply = turn ? (turn.replies || []).map(textOf).join(' | ') : ''
  const calls = (result?.bridgeCalls || []).map((c) => c.m)
  return {
    sameSessionId: Boolean(result?.expectedSessionId) && turn?.sessionId === result.expectedSessionId,
    recallsToken: hasToken(reply, token),
    coldResumeUsed: calls[0] === 'resume' && !calls.includes('create'),
    noErrors: (result?.errors || []).length === 0,
    reply,
  }
}

/** Evaluate timeout/cancel/error isolation result. */
export function evaluateIsolation(result) {
  const iso = result?.isolation || {}
  const ev = iso.eventIsolation || {}
  const kinds = ['timeout', 'cancel', 'error']
  return {
    allScenariosPresent: kinds.every((k) => Boolean(iso[k])),
    allCreateNewSession: kinds.every((k) => iso[k]?.newSession === true),
    noOldTextLeaked: kinds.every((k) => iso[k]?.oldTextLeaked === false),
    noCrossAttributedEvents: ev.crossAttributed === 0,
  }
}

/** Roll a set of boolean criteria into PASS/FAIL. */
export function verdict(criteria) {
  const failed = Object.entries(criteria)
    .filter(([, v]) => v === false)
    .map(([k]) => k)
  return { result: failed.length === 0 ? 'PASS' : 'FAIL', failed, criteria }
}
